param([Parameter(Mandatory=$true)][string]$Source, [Parameter(Mandatory=$true)][string]$Destination, [Parameter(Mandatory=$true)][string]$Pattern, [string]$PreviousTables)
$ErrorActionPreference = 'Stop'
function Get-GeneratedHash([string]$Path) {
    $generatedHash = [Security.Cryptography.SHA256]::Create()
    try { return [Convert]::ToBase64String($generatedHash.ComputeHash([IO.File]::ReadAllBytes($Path))) }
    finally { $generatedHash.Dispose() }
}
# 只清除旧 Tables 实际登记的数据，或带生成器标记的 C#；所有原有 meta 均保留。
$generatedSourceNames = @{}
foreach ($generatedFile in (Get-ChildItem -LiteralPath $Source -Filter $Pattern -File)) { $generatedSourceNames[$generatedFile.Name] = $true }
if ($Pattern -eq '*.bytes' -and $PreviousTables -and (Test-Path -LiteralPath $PreviousTables)) {
    $previousSource = [IO.File]::ReadAllText($PreviousTables)
    foreach ($previousMatch in [regex]::Matches($previousSource, 'loader\("([a-z0-9_]+)"\)')) {
        $previousName = $previousMatch.Groups[1].Value + '.bytes'
        $previousPath = Join-Path $Destination $previousName
        if (-not $generatedSourceNames.ContainsKey($previousName) -and (Test-Path -LiteralPath $previousPath)) { Remove-Item -LiteralPath $previousPath }
    }
}
if ($Pattern -eq '*.cs') {
    foreach ($previousFile in (Get-ChildItem -LiteralPath $Destination -Filter '*.cs' -File)) {
        if (-not $generatedSourceNames.ContainsKey($previousFile.Name) -and [IO.File]::ReadAllText($previousFile.FullName).Contains('<auto-generated>')) { Remove-Item -LiteralPath $previousFile.FullName }
    }
}
# 跳过相同产物，避免 Unity/IDE 映射中的未变化文件被 COPY 截断；仍由唯一 gen.bat 调用。
foreach ($generatedFile in (Get-ChildItem -LiteralPath $Source -Filter $Pattern -File)) {
    $generatedTarget = Join-Path $Destination $generatedFile.Name
    if ((Test-Path -LiteralPath $generatedTarget) -and
        (Get-GeneratedHash $generatedFile.FullName) -eq (Get-GeneratedHash $generatedTarget)) { continue }
    Copy-Item -LiteralPath $generatedFile.FullName -Destination $generatedTarget -Force
}
